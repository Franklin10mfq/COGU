#  ifdef COGU_BUILD_DLL
#    define COGU_API __declspec(dllexport)
#  elif defined(COGU_USE_DLL)
#    define COGU_API __declspec(dllimport)
#  else
#    define COGU_API
#  endif
#elif defined(__GNUC__)
#  define COGU_API __attribute__((visibility("default")))
